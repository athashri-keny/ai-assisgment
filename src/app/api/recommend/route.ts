import { NextResponse , NextRequest } from "next/server";
import OpenAI from "openai";
import 'dotenv/config'
import { products } from "@/data/product";
import z from "zod";
import { zodTextFormat } from "openai/helpers/zod.mjs";

const client = new OpenAI()


const Recommendations = z.object({
  recommendations: z.array(
    z.object({
        id: z.number(),
    })
  ),
});

export async function POST(req: NextRequest) {
    try {
        

        const {text} = await req.json()

        console.log("Text" , text)


        if (!text) {
            return NextResponse.json({
                message: "Error text is required!"
            } , {status: 404})
        }

        const productList = products.map((p) => `${p.id} | ${p.name} | ${p.category} | $${p.price} | ${p.description}`).join("\n");

        const res = await client.responses.parse({
            model: 'gpt-4o-mini-2024-07-18',
            input: text,
            // NOTE: the instructions are generated by the ai
            instructions: `
            You are a product recommendation assistant for an online store.

Below is the complete product catalog. Each product has an id, name,
category, price (in USD), and description.

this are the product list ${productList}

The user will describe what they want. Choose the products from the
catalog that best match their request.

Rules:
- Only recommend products that exist in the catalog above.
- Treat price limits as strict. "Under $500" means the price must be
  below 500.
- Match the category the user asks for. A request for a phone should
  not return a laptop.
- Return at most 5 products, best matches first.
- If nothing matches, return an empty list.

            `,
            text: {
                format: zodTextFormat(Recommendations, "recommendations")
            }
        })

          const parsed = res.output_parsed;
        const ids = parsed?.recommendations.map((e) => e.id)

        return NextResponse.json({
            message: "success",
            ids: ids
        } , {status: 200})



    } catch (error) {
        console.log("Error while running the agent " , error)
        return NextResponse.json({
            message: "Error while running the agent"
        } , {status: 500})
    }
}